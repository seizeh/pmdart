import 'error_reporter.dart';

/// PostgREST 서버가 한 응답에 담는 **최대 행 수**(`db-max-rows`).
///
/// 2026-08-03 운영 REST 에 직접 쏴서 잰 값이다 — `facilities`(전체 24,552행) 기준:
///
///   ?select=id              (상한 미지정)  → 1000
///   ?select=id&limit=5000                 → 1000
///   Range: 0-4999                         → 1000
///   Range: 1000-1999                      → 1000 (content-range: 1000-1999/*)
///
/// 즉 **클라이언트가 무엇을 요구하든 한 응답은 여기서 끊긴다.** offset 페이지네이션은
/// 정상 동작하므로 더 받으려면 `.range()` 로 나눠 받아야 한다.
const int kServerMaxRows = 1000;

/// 목록 조회가 상한에 닿았는지 보고, 닿았으면 보고한다. 행은 그대로 돌려준다.
///
/// ── 왜 필요한가
/// 절단은 **오류가 아니라 데이터처럼 보인다.** 댓글이 1,200개인 글에서 1,000개만
/// 와도 오류도 경고도 없고, 1001번째부터는 "실패" 가 아니라 **"존재하지 않음"** 으로
/// 읽힌다. 앱은 목록이 불완전하다는 사실 자체를 모르고, 사용자는 자기 댓글이
/// 사라졌다고 느낀다.
///
/// 이 프로젝트는 같은 실패 모드를 이미 한 번 겪고 이름을 붙였다 — #234,
/// *"오류가 데이터처럼 보이는 최악의 실패 모드"*. 그때는 오류를 데이터로 착각하는
/// 문제였고 이건 **잘린 데이터를 전부라고 착각하는** 문제다. 구조가 같다.
///
/// ── 무엇을 하지 않는가
/// 행 수를 늘리지 않는다. 상한은 서버가 정하고, 늘려도 언젠가 다시 닿는다.
/// 여기서 하는 일은 **그 순간을 관측 가능하게 만드는 것**이다 — 어떤 목록이 실제로
/// 닿는지 알아야 그 경로에 페이지네이션을 넣을 수 있다. 지금은 어느 것도 안 닿는지,
/// 이미 닿고 있는지조차 알 방법이 없다.
///
/// [limit] 을 준 경우(명시적 상한)에는 그 값을 기준으로 본다.
List<T> guardTruncation<T>(List<T> rows, {required String where, int? limit}) {
  final cap = limit ?? kServerMaxRows;
  if (rows.length >= cap) {
    ErrorReporter.report(
      StateError('list truncated at $cap'),
      where: where,
      extra: {'rows': rows.length, 'cap': cap},
    );
  }
  return rows;
}
